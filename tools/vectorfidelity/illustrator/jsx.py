"""Generate an ExtendScript (.jsx) program that rebuilds a VectorDocument
inside Adobe Illustrator and saves .ai / .svg / .png.

STATUS: NOT VERIFIED. The script is generated and syntax-checked with
Node.js only. It has never been executed inside Illustrator by this
project. ExtendScript is an ES3 dialect; a Node syntax check does not prove
Illustrator compatibility. Coordinate handling (Illustrator uses y-up
document coordinates) must be confirmed on a real Windows machine.
"""

from __future__ import annotations

import hashlib
import json
import os
import re

from ..outputs import check_illustrator_targets
from ..trace import VectorDocument

_TEMPLATE = r"""// Generated by illustrator-ai-assistant / vector-fidelity (phase 1)
// STATUS: NOT VERIFIED in Adobe Illustrator.
// Run manually: Illustrator > File > Scripts > Other Script... and pick this file.
#target illustrator
(function () {
    var W = __W__, H = __H__;
    var OUT_AI = __OUT_AI__;
    var OUT_SVG = __OUT_SVG__;
    var OUT_PNG = __OUT_PNG__;
    var BG = __BG__;
    var REGIONS = __REGIONS__;

    // Safety guard: never overwrite existing files. Checked before any
    // document is created, so a conflict leaves Illustrator untouched.
    // Only the new document created below is modified or saved; documents
    // the user already has open are never accessed.
    var targets = [OUT_AI, OUT_SVG, OUT_PNG];
    var existing = [];
    for (var t = 0; t < targets.length; t++) {
        if (new File(targets[t]).exists) { existing.push(targets[t]); }
    }
    if (existing.length > 0) {
        alert("illustrator-ai-assistant: stopped without changes.\n" +
              "These files already exist and will not be overwritten:\n" +
              existing.join("\n"));
        return;
    }

    function rgb(c) {
        var col = new RGBColor();
        col.red = c[0]; col.green = c[1]; col.blue = c[2];
        return col;
    }
    // Source coordinates are SVG-style (origin top-left, y down).
    // The artboard is set to [0, H, W, 0] so that Illustrator y = H - svgY.
    function toAi(pts) {
        var out = [];
        for (var i = 0; i < pts.length; i++) {
            out.push([pts[i][0], H - pts[i][1]]);
        }
        return out;
    }

    var doc = app.documents.add(DocumentColorSpace.RGB, W, H);
    doc.artboards[0].artboardRect = [0, H, W, 0];
    var layer = doc.layers[0];
    layer.name = "vector-fidelity";

    var bg = layer.pathItems.rectangle(H, 0, W, H); // top, left, width, height
    bg.name = "background";
    bg.stroked = false;
    bg.filled = true;
    bg.fillColor = rgb(BG);

    for (var r = 0; r < REGIONS.length; r++) {
        var reg = REGIONS[r];
        var cp = layer.compoundPathItems.add();
        cp.name = "region-" + r;
        for (var k = 0; k < reg.loops.length; k++) {
            var p = cp.pathItems.add();
            p.setEntirePath(toAi(reg.loops[k]));
            p.closed = true;
            p.stroked = false;
            p.filled = true;
            p.evenodd = true;
            p.fillColor = rgb(reg.color);
        }
    }

    var svgOpts = new ExportOptionsSVG();
    svgOpts.embedRasterImages = false;
    doc.exportFile(new File(OUT_SVG), ExportType.SVG, svgOpts);

    var pngOpts = new ExportOptionsPNG24();
    pngOpts.antiAliasing = true;
    pngOpts.artBoardClipping = true;
    pngOpts.transparency = false;
    doc.exportFile(new File(OUT_PNG), ExportType.PNG24, pngOpts);

    // Save the .ai last: on Illustrator 2021 (Windows, verified), saving first
    // and exporting SVG afterwards left the open document associated with the
    // SVG file. Exporting first keeps the document associated with the .ai.
    doc.saveAs(new File(OUT_AI), new IllustratorSaveOptions());
})();
"""


def build_jsx(doc: VectorDocument, out_ai: str, out_svg: str, out_png: str,
              check_existing: bool = True) -> str:
    """Return the ExtendScript text.

    With ``check_existing`` (default) an OutputConflictError is raised when
    any of the three export targets already exists. The generated script
    also re-checks at run time and stops before creating a document.
    """
    if check_existing:
        check_illustrator_targets([out_ai, out_svg, out_png])
    regions = [
        {"color": list(r.color),
         "loops": [[[round(x, 2), round(y, 2)] for x, y in lp] for lp in r.loops]}
        for r in doc.regions
    ]
    # json.dumps produces valid ES3 literals; forward slashes avoid Windows
    # backslash escaping problems inside ExtendScript File paths.
    rep = {
        "__W__": str(doc.width),
        "__H__": str(doc.height),
        "__OUT_AI__": json.dumps(out_ai.replace("\\", "/")),
        "__OUT_SVG__": json.dumps(out_svg.replace("\\", "/")),
        "__OUT_PNG__": json.dumps(out_png.replace("\\", "/")),
        "__BG__": json.dumps(list(doc.background)),
        "__REGIONS__": json.dumps(regions, separators=(",", ":")),
    }
    text = _TEMPLATE
    for k, v in rep.items():
        text = text.replace(k, v)
    return text


# --------------------------------------------------------------------------
# Integrity verification (used before any automated Illustrator run)
# --------------------------------------------------------------------------
# A generated script consists of a fixed code "skeleton" plus six data lines
# (size, three output paths, background, regions) at fixed positions. A file
# is accepted only when the skeleton is byte-identical to this tool's
# template and every data line is a plain literal of the expected shape, so
# arbitrary ExtendScript cannot pass. tools/illustrator/run_illustrator_jsx.ps1
# repeats the same checks on the Windows side.

JSX_FILENAME = "illustrator_build.jsx"
TARGET_NAMES = ("illustrator_output.ai", "illustrator_output.svg", "illustrator_output.png")
DATA_LINE_INDEXES = (5, 6, 7, 8, 9, 10)  # 0-based
DATA_LINE_PATTERNS = (
    r'^    var W = \d+, H = \d+;$',
    r'^    var OUT_AI = "(?:[^"\\]|\\.)*";$',
    r'^    var OUT_SVG = "(?:[^"\\]|\\.)*";$',
    r'^    var OUT_PNG = "(?:[^"\\]|\\.)*";$',
    r'^    var BG = \[\d+, \d+, \d+\];$',
    r'^    var REGIONS = \[(?:\{"color":\[\d+,\d+,\d+\],"loops":\[(?:\[(?:\[-?\d+(?:\.\d+)?,-?\d+(?:\.\d+)?\],?)+\],?)+\]\},?)*\];$',
)


def normalize_jsx(text: str) -> str:
    return text.replace("\r\n", "\n")


def jsx_sha256(text: str) -> str:
    return hashlib.sha256(normalize_jsx(text).encode("utf-8")).hexdigest()


def _skeleton(lines: list[str]) -> str:
    return "\n".join(l for i, l in enumerate(lines) if i not in DATA_LINE_INDEXES)


def skeleton_sha256() -> str:
    """SHA-256 of the template with the six data lines removed."""
    return hashlib.sha256(_skeleton(_TEMPLATE.split("\n")).encode("utf-8")).hexdigest()


def verify_jsx_text(text: str, jsx_dir: str) -> list[str]:
    """Return a list of problems; empty means the text is a script generated
    by this tool whose three export targets are inside ``jsx_dir``."""
    errors: list[str] = []
    lines = normalize_jsx(text).split("\n")
    if len(lines) <= max(DATA_LINE_INDEXES):
        return ["script is too short to be a generated build script"]
    for idx, pat in zip(DATA_LINE_INDEXES, DATA_LINE_PATTERNS):
        if not re.match(pat, lines[idx]):
            errors.append(f"line {idx + 1} is not an expected data literal")
    if hashlib.sha256(_skeleton(lines).encode("utf-8")).hexdigest() != skeleton_sha256():
        errors.append("script code differs from this tool's template")
    if errors:
        return errors
    base = os.path.abspath(jsx_dir).replace("\\", "/").rstrip("/")
    for idx, name in zip(DATA_LINE_INDEXES[1:4], TARGET_NAMES):
        literal = lines[idx].split(" = ", 1)[1][:-1]
        try:
            value = json.loads(literal)
        except ValueError:
            errors.append(f"line {idx + 1}: output path is not a valid string literal")
            continue
        if os.path.normcase(value) != os.path.normcase(f"{base}/{name}"):
            errors.append(f"line {idx + 1}: output path is not {name} inside the script's folder")
    return errors
