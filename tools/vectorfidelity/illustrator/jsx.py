"""Generate an ExtendScript (.jsx) program that rebuilds a VectorDocument
inside Adobe Illustrator and saves .ai / .svg / .png.

STATUS: NOT VERIFIED. The script is generated and syntax-checked with
Node.js only. It has never been executed inside Illustrator by this
project. ExtendScript is an ES3 dialect; a Node syntax check does not prove
Illustrator compatibility. Coordinate handling (Illustrator uses y-up
document coordinates) must be confirmed on a real Windows machine.
"""

from __future__ import annotations

import json

from ..trace import VectorDocument

_TEMPLATE = r"""// Generated by illustrator-ai-assistant / vector-fidelity (phase 1)
// STATUS: NOT VERIFIED in Adobe Illustrator.
// Run manually: Illustrator > File > Scripts > Other Script... and pick this file.
#target illustrator
(function () {
    var W = __W__, H = __H__;
    var OUT_AI = __OUT_AI__;
    var OUT_SVG = __OUT_SVG__;
    var OUT_PNG = __OUT_PNG__;
    var BG = __BG__;
    var REGIONS = __REGIONS__;

    function rgb(c) {
        var col = new RGBColor();
        col.red = c[0]; col.green = c[1]; col.blue = c[2];
        return col;
    }
    // Source coordinates are SVG-style (origin top-left, y down).
    // The artboard is set to [0, H, W, 0] so that Illustrator y = H - svgY.
    function toAi(pts) {
        var out = [];
        for (var i = 0; i < pts.length; i++) {
            out.push([pts[i][0], H - pts[i][1]]);
        }
        return out;
    }

    var doc = app.documents.add(DocumentColorSpace.RGB, W, H);
    doc.artboards[0].artboardRect = [0, H, W, 0];
    var layer = doc.layers[0];
    layer.name = "vector-fidelity";

    var bg = layer.pathItems.rectangle(H, 0, W, H); // top, left, width, height
    bg.name = "background";
    bg.stroked = false;
    bg.filled = true;
    bg.fillColor = rgb(BG);

    for (var r = 0; r < REGIONS.length; r++) {
        var reg = REGIONS[r];
        var cp = layer.compoundPathItems.add();
        cp.name = "region-" + r;
        for (var k = 0; k < reg.loops.length; k++) {
            var p = cp.pathItems.add();
            p.setEntirePath(toAi(reg.loops[k]));
            p.closed = true;
            p.stroked = false;
            p.filled = true;
            p.evenodd = true;
            p.fillColor = rgb(reg.color);
        }
    }

    doc.saveAs(new File(OUT_AI), new IllustratorSaveOptions());

    var svgOpts = new ExportOptionsSVG();
    svgOpts.embedRasterImages = false;
    doc.exportFile(new File(OUT_SVG), ExportType.SVG, svgOpts);

    var pngOpts = new ExportOptionsPNG24();
    pngOpts.antiAliasing = true;
    pngOpts.artBoardClipping = true;
    pngOpts.transparency = false;
    doc.exportFile(new File(OUT_PNG), ExportType.PNG24, pngOpts);
})();
"""


def build_jsx(doc: VectorDocument, out_ai: str, out_svg: str, out_png: str) -> str:
    regions = [
        {"color": list(r.color),
         "loops": [[[round(x, 2), round(y, 2)] for x, y in lp] for lp in r.loops]}
        for r in doc.regions
    ]
    # json.dumps produces valid ES3 literals; forward slashes avoid Windows
    # backslash escaping problems inside ExtendScript File paths.
    rep = {
        "__W__": str(doc.width),
        "__H__": str(doc.height),
        "__OUT_AI__": json.dumps(out_ai.replace("\\", "/")),
        "__OUT_SVG__": json.dumps(out_svg.replace("\\", "/")),
        "__OUT_PNG__": json.dumps(out_png.replace("\\", "/")),
        "__BG__": json.dumps(list(doc.background)),
        "__REGIONS__": json.dumps(regions, separators=(",", ":")),
    }
    text = _TEMPLATE
    for k, v in rep.items():
        text = text.replace(k, v)
    return text
